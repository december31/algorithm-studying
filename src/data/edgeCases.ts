// Cache computed test cases to avoid re-running evaluation
const enrichedCache = new Map<string, TestCase[]>();

/**
 * Returns an enriched list of 10 test cases:
 * - Cases 1..3: Public sample cases (isHidden = false)
 * - Cases 4..10: Hidden edge & stress cases (isHidden = true)
 */
export function getEnrichedTestCases(problem: Problem): TestCase[] {
  if (enrichedCache.has(problem.id)) {
    return enrichedCache.get(problem.id)!;
  }

  // Ensure first 3 are explicitly marked as public samples
  const sampleCases: TestCase[] = problem.testCases.map((tc, idx) => ({
    ...tc,
    id: idx + 1,
    isHidden: false,
  }));

  const hiddenInputs = edgeCasesInputs[problem.id];
  if (!hiddenInputs || hiddenInputs.length === 0) {
    enrichedCache.set(problem.id, sampleCases);
    return sampleCases;
  }

  // Compile reference solution evaluator
  let evaluator: ((...args: any[]) => any) | null = null;
  try {
    evaluator = new Function(problem.solutionCode + '; return ' + problem.functionName)();
  } catch {
    evaluator = null;
  }

  const hiddenCases: TestCase[] = hiddenInputs.map((input, idx) => {
    const caseId = sampleCases.length + idx + 1;
    let expected: any = null;

    if (evaluator) {
      try {
        const cloned = JSON.parse(JSON.stringify(input));
        expected = evaluator(...cloned);
      } catch {
        expected = null;
      }
    }

    return {
      id: caseId,
      input,
      expected,
      inputDisplay: formatDisplay(input),
      expectedDisplay: typeof expected === 'object' ? JSON.stringify(expected) : String(expected),
      isHidden: true,
    };
  });

  const fullSuite = [...sampleCases, ...hiddenCases];
  enrichedCache.set(problem.id, fullSuite);
  return fullSuite;
}
