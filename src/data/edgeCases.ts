// Helper to stringify display values cleanly
function formatDisplay(input: any[]): string {
  if (!input || input.length === 0) return '()';
  return input
    .map((arg) => {
      if (typeof arg === 'string') return `"${arg}"`;
      if (Array.isArray(arg)) {
        if (arg.length > 5) return `[${arg.slice(0, 4).map((x) => JSON.stringify(x)).join(', ')}, ... (${arg.length} items)]`;
        return JSON.stringify(arg);
      }
      return String(arg);
    })
    .join(', ');
}

